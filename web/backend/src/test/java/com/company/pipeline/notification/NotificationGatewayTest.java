package com.company.pipeline.notification;

import static org.assertj.core.api.Assertions.assertThat;

import java.util.Map;
import javax.sql.DataSource;
import okhttp3.mockwebserver.MockResponse;
import okhttp3.mockwebserver.MockWebServer;
import okhttp3.mockwebserver.RecordedRequest;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.ObjectProvider;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.mail.javamail.JavaMailSender;

/**
 * 발송 채널을 화면 설정으로 굴리는 부분(2026-09-20). 문자·카카오는 같은 HTTP 릴레이를 쓰고,
 * 규격 차이(주소·헤더·본문·성공 판정)는 전부 설정으로 받는다 - 대행사를 코드에 박지 않았는지 본다.
 *
 * <p>DB 는 H2 인메모리로 아웃박스 표만 만들어 쓴다. Postgres 전용 문법을 피해 이 테스트가
 * Testcontainers(이 환경에서 자주 실패) 없이 돌게 한다.
 */
class NotificationGatewayTest {

    private MockWebServer gateway;
    private DataSource dataSource;
    private JdbcTemplate jdbc;

    @BeforeEach
    void setUp() throws Exception {
        gateway = new MockWebServer();
        gateway.start();
        // 재시도 백오프 SQL 이 Postgres 문법(now() + interval '2 minutes')이라 H2 를 Postgres 호환 모드로 연다.
        // 그냥 H2 로 열면 그 UPDATE 만 조용히 실패해 «재시도로 안 바뀐다»는 가짜 실패가 난다(실측).
        org.springframework.jdbc.datasource.SimpleDriverDataSource h2 =
                new org.springframework.jdbc.datasource.SimpleDriverDataSource();
        h2.setDriverClass(org.h2.Driver.class);
        h2.setUrl("jdbc:h2:mem:notify-" + System.nanoTime() + ";MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1");
        h2.setUsername("sa");
        dataSource = h2;
        jdbc = new JdbcTemplate(dataSource);
        jdbc.execute("""
                CREATE TABLE notification_delivery (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    channel_type VARCHAR(20),
                    severity_rank INT DEFAULT 0,
                    target_address VARCHAR(255),
                    subject VARCHAR(255),
                    body VARCHAR(1000),
                    status VARCHAR(20),
                    attempt_count INT DEFAULT 0,
                    max_attempts INT DEFAULT 5,
                    first_attempt_at TIMESTAMP,
                    sent_at TIMESTAMP,
                    next_attempt_at TIMESTAMP,
                    failure_reason VARCHAR(40),
                    failure_detail VARCHAR(1000),
                    updated_at TIMESTAMP)
                """);
        jdbc.execute("""
                CREATE TABLE notification_channel_config (
                    channel_type VARCHAR(20) PRIMARY KEY,
                    enabled BOOLEAN,
                    config_json VARCHAR(4000),
                    encrypted_secret VARCHAR(500),
                    secret_hint VARCHAR(10),
                    updated_by VARCHAR(255),
                    updated_at TIMESTAMP)
                """);
        jdbc.update("INSERT INTO notification_channel_config (channel_type, enabled, config_json) VALUES ('KAKAO', true, '{}')");
        jdbc.update("INSERT INTO notification_channel_config (channel_type, enabled, config_json) VALUES ('SMS', true, '{}')");
    }

    @AfterEach
    void tearDown() throws Exception {
        gateway.shutdown();
    }

    @Test
    void kakaoUsesScreenSettings_templateAndHeaderAndSecret() throws Exception {
        gateway.enqueue(new MockResponse().setResponseCode(200).setBody("{\"header\":{\"resultCode\":0}}"));
        long id = insertDelivery("KAKAO", "01012345678", "[관제] CRITICAL 알림", "적재 지연 30분");
        NotificationService service = service(settings(Map.of(
                "url", gateway.url("/alimtalk").toString(),
                "headers", "Authorization: Bearer {secret}",
                "bodyTemplate", "{\"senderKey\":\"{senderKey}\",\"templateCode\":\"{templateCode}\","
                        + "\"to\":\"{to}\",\"text\":\"{text}\"}",
                "senderKey", "SK-1", "templateCode", "TPL-1",
                "successPath", "header.resultCode", "successValue", "0"), "API-KEY-XYZ"));

        service.dispatch();

        RecordedRequest sent = gateway.takeRequest(5, java.util.concurrent.TimeUnit.SECONDS);
        assertThat(sent).as("게이트웨이로 요청이 가야 한다").isNotNull();
        assertThat(sent.getPath()).isEqualTo("/alimtalk");
        // 비밀값은 헤더 치환자로 들어간다(대행사마다 헤더 이름이 달라 설정으로 받는다).
        assertThat(sent.getHeader("Authorization")).isEqualTo("Bearer API-KEY-XYZ");
        String body = sent.getBody().readUtf8();
        assertThat(body).contains("\"senderKey\":\"SK-1\"", "\"templateCode\":\"TPL-1\"",
                "\"to\":\"01012345678\"", "적재 지연 30분");
        assertThat(status(id)).isEqualTo("SENT");
    }

    @Test
    void kakaoTreatsBusinessFailureAsFailure_evenOnHttp200() throws Exception {
        // 대행사는 HTTP 200 으로 주면서 본문에 실패를 담는 일이 흔하다. 성공 판정 규칙이 그걸 잡는다.
        gateway.enqueue(new MockResponse().setResponseCode(200)
                .setBody("{\"header\":{\"resultCode\":3001,\"resultMessage\":\"템플릿 불일치\"}}"));
        long id = insertDelivery("KAKAO", "01012345678", "제목", "본문");
        NotificationService service = service(settings(Map.of(
                "url", gateway.url("/alimtalk").toString(),
                "successPath", "header.resultCode", "successValue", "0"), "KEY"));

        service.dispatch();

        assertThat(status(id)).isEqualTo("RETRY");
        Map<String, Object> row = jdbc.queryForMap(
                "SELECT failure_reason, failure_detail FROM notification_delivery WHERE id=?", id);
        assertThat(row.get("failure_reason")).isEqualTo("KAKAO_ERROR");
        assertThat((String) row.get("failure_detail")).contains("성공 판정 불일치", "3001");
    }

    @Test
    void withoutSuccessRule_http200IsEnough() throws Exception {
        gateway.enqueue(new MockResponse().setResponseCode(200).setBody("ok"));
        long id = insertDelivery("KAKAO", "01012345678", "제목", "본문");
        NotificationService service = service(settings(Map.of(
                "url", gateway.url("/alimtalk").toString()), "KEY"));

        service.dispatch();

        assertThat(status(id)).isEqualTo("SENT");
    }

    @Test
    void noUrl_isNoRelay_notCrash() {
        long id = insertDelivery("KAKAO", "01012345678", "제목", "본문");
        NotificationService service = service(settings(Map.of(), ""));

        service.dispatch();

        assertThat(status(id)).isEqualTo("RETRY");
        assertThat(jdbc.queryForObject(
                "SELECT failure_reason FROM notification_delivery WHERE id=?", String.class, id))
                .isEqualTo("NO_RELAY");
    }

    private long insertDelivery(String channel, String to, String subject, String body) {
        jdbc.update("INSERT INTO notification_delivery (channel_type, severity_rank, target_address, subject, body, "
                + "status, next_attempt_at, attempt_count, max_attempts) VALUES (?, 0, ?, ?, ?, 'PENDING', "
                + "CURRENT_TIMESTAMP, 0, 5)", channel, to, subject, body);
        return jdbc.queryForObject("SELECT MAX(id) FROM notification_delivery", Long.class);
    }

    private String status(long id) {
        return jdbc.queryForObject("SELECT status FROM notification_delivery WHERE id=?", String.class, id);
    }

    /** 화면에서 저장한 설정을 흉내 낸다(암호화는 그대로 통과시키는 가짜 구현). */
    private ChannelSettingsService settings(Map<String, String> values, String secret) {
        StringBuilder json = new StringBuilder("{");
        values.forEach((k, v) -> json.append(json.length() > 1 ? "," : "")
                .append('"').append(k).append("\":\"").append(v.replace("\\", "\\\\").replace("\"", "\\\"")).append('"'));
        json.append("}");
        jdbc.update("UPDATE notification_channel_config SET config_json=?, encrypted_secret=? WHERE channel_type='KAKAO'",
                json.toString(), secret == null || secret.isBlank() ? null : secret);
        return new ChannelSettingsService(dataSource, new PlainCrypto(),
                "", "", "", "", "false", "false", "",
                "", "", "application/json", "", "",
                "", "", "application/json", "", "", "", "", "", "", "");
    }

    private NotificationService service(ChannelSettingsService settings) {
        return new NotificationService(dataSource, new NoMailSender(), settings, false, true, true);
    }

    /** 테스트용 - 암·복호화를 하지 않는다(키 관리가 이 테스트의 관심사가 아니다). */
    private static class PlainCrypto implements com.company.pipeline.common.crypto.PasswordCryptoService {
        @Override
        public String encrypt(String plain) {
            return plain;
        }

        @Override
        public String decrypt(String cipher) {
            return cipher;
        }
    }

    private static class NoMailSender implements ObjectProvider<JavaMailSender> {
        @Override
        public JavaMailSender getObject(Object... args) {
            return null;
        }

        @Override
        public JavaMailSender getObject() {
            return null;
        }

        @Override
        public JavaMailSender getIfAvailable() {
            return null;
        }

        @Override
        public JavaMailSender getIfUnique() {
            return null;
        }

        @Override
        public java.util.stream.Stream<JavaMailSender> stream() {
            return java.util.stream.Stream.empty();
        }
    }
}
