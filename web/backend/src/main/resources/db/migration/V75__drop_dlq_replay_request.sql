-- DLQ 재처리 요청 · 승인 표(V44)를 지운다.
--
-- ■ 이유
--   CDC 싱크의 실패 정책을 «버리고 계속»(errors.tolerance=all + DLQ 토픽)에서 «멈춤»(none)으로 바꿨다(2026-09-17).
--   거부된 건은 오프셋이 그 자리에 멈춰 고치고 재시작하면 그 건부터 다시 들어오므로 DLQ 에 쌓일 것이 없고,
--   재처리 요청 · 승인 흐름도 쓰이지 않는다. 백엔드 API · 서비스와 화면 API 함수도 함께 뺐다.
--
-- ■ 지워도 되는 근거
--   행 수를 확인했다 - 로컬 0건, 운영(MSA) 0건(2026-09-17, 읽기 전용 조회). 재처리 화면은 한 번도 붙은 적이 없다.
--
-- ■ 남긴 것
--   기존 dlq.pipeline-{id} Kafka 토픽은 이 마이그레이션이 건드리지 않는다(DB 가 아니다). 파이프라인을 지울 때
--   KafkaTopicCleanupService 가 함께 지운다.
-- =============================================================================
DROP TABLE IF EXISTS dlq_replay_request;
