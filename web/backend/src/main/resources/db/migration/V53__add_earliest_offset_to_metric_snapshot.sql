-- 지표 보정: 토픽의 가장 오래된 offset 을 함께 기록한다.
--
-- retention 으로 토픽 앞부분이 삭제되면 그 구간은 컨슈머가 읽을 수 없으므로 "미처리"도
-- "처리"도 아니다. 그런데 committed offset 이 그보다 작으면(컨슈머 그룹이 처음 붙어 0 인
-- 경우 등) 삭제된 구간까지 lag 과 처리 건수에 잡혀 실제보다 크게 나온다.
--   실측(2026-08-25): 스냅샷 10만 건인데 lag 20만 · 일 누적 처리 20만으로 표시.
--   토픽 earliest=100000 / latest=200000, 실제 소비 가능 레코드는 10만 건이었다.
--
-- 하한 계산에 쓰려면 "그 시점의 earliest" 가 필요해 스냅샷에 같이 남긴다.
-- 기존 행은 NULL 이며, 호출부는 NULL 을 0(=보정 없음)으로 다룬다.
-- -----------------------------------------------------------------------------
ALTER TABLE pipeline_metric_snapshot ADD COLUMN earliest_offset BIGINT;

COMMENT ON COLUMN pipeline_metric_snapshot.earliest_offset IS
    '수집 시점 토픽 각 파티션의 가장 오래된 offset 합. lag·처리 건수의 하한 보정에 쓴다.';
